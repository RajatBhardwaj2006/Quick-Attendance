-- QuickAttendance schema for Supabase PostgreSQL.
-- This app uses a server-side Supabase secret/service key. NEVER expose it in a browser.
create extension if not exists pgcrypto;

create table if not exists public.teacher (
  teacher_id bigint generated by default as identity primary key,
  user_name text not null unique,
  email text not null unique,
  password_hash text not null,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.students (
  student_id bigint generated by default as identity primary key,
  user_name text not null unique,
  email text not null unique,
  password_hash text not null,
  name text not null,
  face_embedding jsonb,
  voice_embedding jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.subjects (
  subject_id bigint generated by default as identity primary key,
  subject_code text not null,
  name text not null default 'Not Defined',
  section text not null default 'N/A',
  join_code text not null unique,
  teacher_id bigint references public.teacher(teacher_id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.subject_student (
  subject_id bigint not null references public.subjects(subject_id) on delete cascade,
  student_id bigint not null references public.students(student_id) on delete cascade,
  enrolled_at timestamptz not null default now(),
  primary key(subject_id, student_id)
);

create table if not exists public.attendance_sessions (
  id bigint generated by default as identity primary key,
  subject_id bigint not null references public.subjects(subject_id) on delete cascade,
  teacher_id bigint not null references public.teacher(teacher_id) on delete cascade,
  method text not null check (method in ('manual','face','voice')),
  started_at timestamptz not null default now(),
  ended_at timestamptz
);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.attendance_sessions(id) on delete cascade,
  timestamp timestamptz not null default now(),
  subject_id bigint not null references public.subjects(subject_id) on delete cascade,
  student_id bigint not null references public.students(student_id) on delete cascade,
  if_present boolean not null default false,
  method text not null check (method in ('manual','face','voice')),
  unique(session_id, student_id)
);

create index if not exists idx_subjects_teacher on public.subjects(teacher_id);
create index if not exists idx_enrollment_student on public.subject_student(student_id);
create index if not exists idx_attendance_student_time on public.attendance(student_id,timestamp desc);
create index if not exists idx_attendance_subject_time on public.attendance(subject_id,timestamp desc);

-- This prototype expects all table access to happen server-side through Streamlit.
-- Enable RLS and do not expose a service/secret key to client-side code.
alter table public.teacher enable row level security;
alter table public.students enable row level security;
alter table public.subjects enable row level security;
alter table public.subject_student enable row level security;
alter table public.attendance_sessions enable row level security;
alter table public.attendance enable row level security;
